def _is_page_element_ignored(page_element):
    raw = page_element.raw if isinstance(page_element.raw, dict) else {}
    return str(raw.get('governance_status') or '').strip() == 'ignored'


class AppPageMapViewSet(viewsets.ReadOnlyModelViewSet):
    """Read persisted page-map assets generated by controlled inspections."""

    serializer_class = AppPageNodeSerializer
    permission_classes = [IsAuthenticated]
    pagination_class = AppPagination
    filter_backends = [DjangoFilterBackend, SearchFilter]
    filterset_fields = ['project', 'app_package', 'platform', 'activity']
    search_fields = ['title', 'business_name', 'activity', 'page_signature']

    def get_queryset(self):
        queryset = (
            AppPageNode.objects
            .select_related('project', 'app_package', 'first_seen_run', 'last_seen_run')
            .prefetch_related('elements')
            .order_by('-updated_at')
        )
        search = str(self.request.query_params.get('search') or '').strip()
        if search:
            queryset = queryset.filter(
                Q(title__icontains=search)
                | Q(business_name__icontains=search)
                | Q(activity__icontains=search)
                | Q(page_signature__icontains=search)
                | Q(elements__text__icontains=search)
                | Q(elements__content_desc__icontains=search)
                | Q(elements__resource_id__icontains=search)
            ).distinct()
        return queryset

    @action(detail=False, methods=['get'], url_path='summary')
    def summary(self, request):
        queryset = self.filter_queryset(self.get_queryset())
        page_count = queryset.count()
        element_queryset = AppPageElement.objects.filter(page__in=queryset)
        transition_queryset = AppPageTransition.objects.filter(from_page__in=queryset)
        activity_count = queryset.exclude(activity='').values('activity').distinct().count()
        top_pages = (
            queryset
            .annotate(element_total=Count('elements'), transition_total=Count('outgoing_transitions'))
            .order_by('-visit_count', '-updated_at')[:8]
        )
        return Response({
            'success': True,
            'data': {
                'page_count': page_count,
                'activity_count': activity_count,
                'element_count': element_queryset.count(),
                'clickable_count': element_queryset.filter(clickable=True).count(),
                'transition_count': transition_queryset.count(),
                'top_pages': [
                    {
                        'id': page.id,
                        'title': page.business_name or page.title,
                        'activity': page.activity,
                        'visit_count': page.visit_count,
                        'element_count': page.element_total,
                        'transition_count': page.transition_total,
                    }
                    for page in top_pages
                ],
            },
        })

    @action(detail=False, methods=['get'], url_path='element-candidates')
    def element_candidates(self, request):
        queryset = (
            AppPageElement.objects
            .select_related('page', 'page__project', 'page__app_package')
            .filter(enabled=True)
            .order_by('-clickable', '-seen_count', 'page_id', 'id')
        )
        project_id = request.query_params.get('project')
        app_package_id = request.query_params.get('app_package')
        legacy_page_filter = bool(
            request.query_params.get('page')
            and not request.query_params.get('page_id')
            and not request.query_params.get('node_id')
        )
        page_id = request.query_params.get('page_id') or request.query_params.get('node_id') or request.query_params.get('page')
        role = str(request.query_params.get('role') or '').strip()
        search = str(request.query_params.get('search') or '').strip()
        only_clickable = str(request.query_params.get('clickable') or '').lower() in {'1', 'true', 'yes'}
        include_ignored = str(request.query_params.get('include_ignored') or '').lower() in {'1', 'true', 'yes'}

        if project_id:
            queryset = queryset.filter(page__project_id=project_id)
        if app_package_id:
            queryset = queryset.filter(page__app_package_id=app_package_id)
        if page_id:
            queryset = queryset.filter(page_id=page_id)
        if role:
            queryset = queryset.filter(role=role)
        if only_clickable:
            queryset = queryset.filter(clickable=True)
        if search:
            queryset = queryset.filter(
                Q(text__icontains=search)
                | Q(content_desc__icontains=search)
                | Q(resource_id__icontains=search)
                | Q(class_name__icontains=search)
                | Q(page__title__icontains=search)
            )
        queryset = queryset.exclude(risk_level='forbidden')
        if not include_ignored:
            queryset = [element for element in queryset if not _is_page_element_ignored(element)]
        page = None if legacy_page_filter else self.paginate_queryset(queryset)
        if page is not None:
            serializer = AppPageElementSerializer(page, many=True, context={'request': request})
            return self.get_paginated_response(serializer.data)
        serializer = AppPageElementSerializer(queryset[:100], many=True, context={'request': request})
        return Response({'success': True, 'data': serializer.data})

