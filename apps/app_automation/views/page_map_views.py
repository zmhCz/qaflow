def _resource_tail(resource_id):
    text = str(resource_id or '').strip()
    return text.rsplit('/', 1)[-1] if text else ''


def _page_element_tokens(page):
    tokens = set()
    elements = getattr(page, '_prefetched_objects_cache', {}).get('elements')
    if elements is None:
        elements = page.elements.filter(enabled=True)[:120]
    for element in elements:
        for value in (element.resource_id, element.text, element.content_desc):
            token = _normalize_page_token(value)
            if token:
                tokens.add(token)
        tail = _normalize_page_token(_resource_tail(element.resource_id))
        if tail:
            tokens.add(tail)
    return tokens


def _normalize_page_token(value):
    text = str(value or '').strip().lower()
    if not text:
        return ''
    text = text.rsplit('/', 1)[-1]
    text = re.sub(r'\s+', '', text)
    return text[:120]


def _score_duplicate_page(target_page, target_tokens, candidate_page, candidate_tokens):
    score = 0
    reasons = []

    target_name = str(target_page.business_name or '').strip()
    candidate_name = str(candidate_page.business_name or '').strip()
    if target_name and candidate_name and target_name == candidate_name:
        score += 30
        reasons.append('页面业务名一致')

    if target_page.semantic_signature and target_page.semantic_signature == candidate_page.semantic_signature:
        score += 35
        reasons.append('语义签名一致')

    if target_page.activity and target_page.activity == candidate_page.activity:
        score += 20
        reasons.append('Activity 一致')

    if target_page.screen_size and target_page.screen_size == candidate_page.screen_size:
        score += 5
        reasons.append('屏幕尺寸一致')

    union_count = len(target_tokens | candidate_tokens)
    shared_count = len(target_tokens & candidate_tokens)
    if union_count:
        overlap_score = round((shared_count / union_count) * 40)
        if overlap_score:
            score += overlap_score
            reasons.append(f'控件特征重叠 {shared_count}/{union_count}')

    if target_page.activity and target_page.activity != candidate_page.activity and score < 70:
        score = max(0, score - 15)
        reasons.append('Activity 不同，已降权')

    return min(score, 100), reasons


def _build_locator_key(page_element, role):
    raw = page_element.resource_id or page_element.text or page_element.content_desc or f'element_{page_element.id}'
    tail = _resource_tail(raw) or raw
    key = re.sub(r'[^0-9a-zA-Z_]+', '_', str(tail).strip()).strip('_').lower()
    role_prefix = re.sub(r'[^0-9a-zA-Z_]+', '_', str(role or 'control')).strip('_').lower()
    if not key:
        key = f'element_{page_element.id}'
    if role_prefix and not key.startswith(f'{role_prefix}_'):
        key = f'{role_prefix}_{key}'
    return key[:80]


def _unique_element_name(base_name):
    base = re.sub(r'\.+', '.', str(base_name or 'semantic_v2.element').strip('.'))[:180]
    if not AppElement.objects.filter(name=base).exists():
        return base
    index = 2
    while True:
        candidate = f'{base}.{index}'
        if not AppElement.objects.filter(name=candidate).exists():
            return candidate
        index += 1
