    @action(detail=False, methods=['post'], url_path='promote-element')
    def promote_element(self, request):
        """Promote a page-map control snapshot into a pending semantic_v2 selector element."""
        element_id = request.data.get('element_id')
        page_element = (
            AppPageElement.objects
            .select_related('page', 'page__project', 'page__app_package')
            .filter(id=element_id)
            .first()
        )
        if not page_element:
            return Response({'success': False, 'message': '未找到页面地图控件候选'}, status=404)
        if page_element.risk_level == 'forbidden':
            return Response({'success': False, 'message': '该控件命中高风险策略，不允许直接入库'}, status=400)

        element, created = _promote_page_element(page_element, request.user, request.data)
        return Response({
            'success': True,
            'message': '已加入 semantic_v2 语义库，状态为待验证' if created else '已更新语义库候选元素',
            'data': AppElementSerializer(element, context={'request': request}).data,
        })

    @action(detail=False, methods=['post'], url_path='bulk-promote-elements')
    def bulk_promote_elements(self, request):
        """Promote selected page-map controls in one batch."""
        element_ids = request.data.get('element_ids') or []
        if not isinstance(element_ids, list) or not element_ids:
            return Response({'success': False, 'message': '请选择要入库的控件候选'}, status=400)

        page_elements = (
            AppPageElement.objects
            .select_related('page', 'page__project', 'page__app_package')
            .filter(id__in=element_ids)
            .exclude(risk_level='forbidden')
        )
        created = []
        updated = []
        for page_element in page_elements:
            element, is_created = _promote_page_element(page_element, request.user, request.data)
            serialized = AppElementSerializer(element, context={'request': request}).data
            if is_created:
                created.append(serialized)
            else:
                updated.append(serialized)

        skipped_count = len(set(element_ids)) - len(created) - len(updated)
        return Response({
            'success': True,
            'message': f'批量入库完成，新增 {len(created)} 个，更新 {len(updated)} 个，跳过 {skipped_count} 个',
            'data': {
                'created': created,
                'updated': updated,
                'skipped_count': skipped_count,
            },
        })

    @action(detail=False, methods=['post'], url_path='govern-elements')
    def govern_elements(self, request):
        """Mark page-map control candidates as ignored or restore them."""
        element_ids = request.data.get('element_ids') or []
        status_value = str(request.data.get('governance_status') or '').strip()
        if not isinstance(element_ids, list) or not element_ids:
            return Response({'success': False, 'message': '请选择要治理的控件候选'}, status=400)
        if status_value not in {'ignored', 'active'}:
            return Response({'success': False, 'message': 'governance_status 只能是 ignored 或 active'}, status=400)

        elements = AppPageElement.objects.filter(id__in=element_ids).exclude(risk_level='forbidden')
        updated_count = 0
        for element in elements:
            raw = dict(element.raw or {})
            if status_value == 'ignored':
                raw['governance_status'] = 'ignored'
                raw['governance_reason'] = str(request.data.get('reason') or '人工标记无需维护').strip()[:255]
            else:
                raw.pop('governance_status', None)
                raw.pop('governance_reason', None)
            element.raw = raw
            element.save(update_fields=['raw', 'updated_at'])
            updated_count += 1

        return Response({
            'success': True,
            'message': '控件候选已标记为无需维护' if status_value == 'ignored' else '控件候选已恢复',
            'data': {
                'updated_count': updated_count,
                'governance_status': status_value,
            },
        })

